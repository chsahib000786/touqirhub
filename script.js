/* =========================
   NORMALIZE SEARCH
========================= */

function normalizeText(text) {

  return text
    .toLowerCase()
    .replace(/[?!.,'"`]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

}


/* =========================
   SMART SEARCH
========================= */

function smartSearch() {

  const input = document.getElementById("searchInput");
  const resultsBox = document.getElementById("searchResults");

  if (!input || !resultsBox) return;

  const query = normalizeText(input.value);

  resultsBox.innerHTML = "";

  if (!query) return;

  const words = query
    .split(/\s+/)
    .filter(word => word.length >= 2);

  const results = searchDatabase
    .map(item => {

      let score = 0;

      const title = normalizeText(item.title);
      const description = normalizeText(item.description);

      const keywords = item.keywords.map(keyword =>
        normalizeText(keyword)
      );

      /* Exact title */
      if (title === query) {
        score += 150;
      }

      /* Exact keyword */
      keywords.forEach(keyword => {
        if (keyword === query) {
          score += 100;
        }
      });

      /* Phrase in title */
      if (title.includes(query)) {
        score += 70;
      }

      /* Phrase in description */
      if (description.includes(query)) {
        score += 30;
      }

      /* Individual words */
      words.forEach(word => {

        if (title.includes(word)) {
          score += 25;
        }

        if (description.includes(word)) {
          score += 10;
        }

        keywords.forEach(keyword => {

          if (keyword === word) {
            score += 35;
          }

          else if (keyword.includes(word)) {
            score += 18;
          }

        });

      });

      return {
        ...item,
        score
      };

    })
    .filter(item => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 6);


  /* No results */
  if (results.length === 0) {

    resultsBox.innerHTML = `
      <div class="search-result">
        <h3>No results found</h3>
        <p>
          Try searching for age calculator, loan, weather,
          meditation, sleep, kids or fitness.
        </p>
      </div>
    `;

    return;
  }


  /* Show results */
  results.forEach(item => {

    const result = document.createElement("a");

    result.href = item.url;
    result.className = "search-result";

    result.innerHTML = `
      <h3>${item.title}</h3>
      <p>${item.description}</p>
    `;

    resultsBox.appendChild(result);

  });

}


/* =========================
   MOBILE MENU
========================= */

function toggleMenu() {

  const menu = document.getElementById("mobileMenu");

  if (!menu) return;

  menu.classList.toggle("active");

}


/* =========================
   CLOSE MOBILE MENU
========================= */

document.addEventListener("DOMContentLoaded", function () {

  const menuLinks =
    document.querySelectorAll("#mobileMenu a");

  menuLinks.forEach(link => {

    link.addEventListener("click", function () {

      const menu =
        document.getElementById("mobileMenu");

      if (menu) {
        menu.classList.remove("active");
      }

    });

  });

});


/* =========================
   SEARCH FOCUS
========================= */

function focusSearch() {

  const searchInput =
    document.getElementById("searchInput");

  if (!searchInput) return;

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

  setTimeout(function () {
    searchInput.focus();
  }, 500);

}


/* =========================
   WEATHER SEARCH
========================= */

function searchWeather() {

  const cityInput =
    document.getElementById("cityInput");

  const weatherResult =
    document.getElementById("weatherResult");

  if (!cityInput || !weatherResult) return;

  const city =
    cityInput.value.trim();

  if (city === "") {

    weatherResult.innerHTML = `
      <p>Please enter a city name.</p>
    `;

    return;
  }

  weatherResult.innerHTML = `
    <p>
      Weather information for
      <strong>${city}</strong>
      will appear here.
    </p>

    <p>
      Weather service will be connected in the next step.
    </p>
  `;

}